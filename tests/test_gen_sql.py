import re

from erp_spec_forge.gen_sql import generate_sql


def test_sql_contains_all_tables(system):
    sql = generate_sql(system)
    tables = re.findall(r"CREATE TABLE `(\w+)`", sql)
    assert len(tables) == len(system.entities) == 46
    assert len(set(tables)) == 46


def test_sql_fk_constraints(system):
    sql = generate_sql(system)
    assert "FOREIGN KEY (`goods_id`) REFERENCES `goods`" in sql
    assert "CONSTRAINT `fk_sales_order_item_order_id`" in sql


def test_sql_enum_check(system):
    sql = generate_sql(system)
    assert "CHECK (`status` IN ('normal', 'stopped'))" in sql


def test_sql_pk_and_comment(system):
    sql = generate_sql(system)
    assert "PRIMARY KEY (`id`)" in sql
    assert "COMMENT='供应商'" in sql
    assert sql.startswith("-- Generated by erp-spec-forge")


def test_sql_decimal_precision(system):
    sql = generate_sql(system)
    assert "DECIMAL(12,2)" in sql
    assert "DECIMAL(5,2)" in sql
