"""OpenAPI 3.1 generator: standard CRUD paths per entity + response envelope."""
from __future__ import annotations

from .loader import System

_OA_TYPE = {
    "pk": {"type": "integer", "format": "int64"},
    "fk": {"type": "integer", "format": "int64"},
    "string": {"type": "string"},
    "text": {"type": "string"},
    "int": {"type": "integer"},
    "decimal": {"type": "number", "format": "double"},
    "bool": {"type": "boolean"},
    "date": {"type": "string", "format": "date"},
    "datetime": {"type": "string", "format": "date-time"},
    "enum": {"type": "string"},
    "json": {},
}


def _plural(name: str) -> str:
    return name + "s" if not name.endswith("s") else name


def _schema(e) -> dict:
    props, required = {}, []
    for f in e.fields:
        if f.type == "json":
            props[f.name] = {"type": "object", "additionalProperties": True}
        else:
            props[f.name] = dict(_OA_TYPE[f.type])
        if f.values:
            props[f.name]["enum"] = list(f.values)
        if f.comment:
            props[f.name]["description"] = f.comment
        if f.required and f.type != "pk":
            required.append(f.name)
    schema = {"type": "object", "properties": props}
    if required:
        schema["required"] = required
    return schema


def _envelope(data_ref: str | None, array: bool = False) -> dict:
    if data_ref is None:
        data: dict = {"type": "null"}
    elif array:
        data = {"type": "array", "items": {"$ref": data_ref}}
    else:
        data = {"$ref": data_ref}
    return {
        "type": "object",
        "properties": {"code": {"type": "integer", "description": "0 = success"}, "msg": {"type": "string"}, "data": data},
        "required": ["code", "msg"],
    }


def generate_openapi(system: System) -> dict:
    paths: dict = {}
    schemas: dict = {}
    for e in system.entities:
        ref = f"#/components/schemas/{e.name}"
        schemas[e.name] = _schema(e)
        base = "/" + _plural(e.name)
        paths[base] = {
            "get": {
                "summary": f"分页查询 {e.display}",
                "tags": [e.domain],
                "parameters": [
                    {"name": "page", "in": "query", "schema": {"type": "integer", "default": 1}},
                    {"name": "page_size", "in": "query", "schema": {"type": "integer", "default": 20}},
                    {"name": "keyword", "in": "query", "schema": {"type": "string"}},
                ],
                "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": _envelope(ref, array=True)}}}},
            },
            "post": {
                "summary": f"新建 {e.display}",
                "tags": [e.domain],
                "requestBody": {"content": {"application/json": {"schema": {"$ref": ref}}}},
                "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": _envelope(ref)}}}},
            },
        }
        item = base + "/{id}"
        paths[item] = {
            "get": {
                "summary": f"查看 {e.display} 详情",
                "tags": [e.domain],
                "parameters": [{"name": "id", "in": "path", "required": True, "schema": {"type": "integer", "format": "int64"}}],
                "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": _envelope(ref)}}}},
            },
            "put": {
                "summary": f"更新 {e.display}",
                "tags": [e.domain],
                "parameters": [{"name": "id", "in": "path", "required": True, "schema": {"type": "integer", "format": "int64"}}],
                "requestBody": {"content": {"application/json": {"schema": {"$ref": ref}}}},
                "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": _envelope(ref)}}}},
            },
            "delete": {
                "summary": f"删除 {e.display}",
                "tags": [e.domain],
                "parameters": [{"name": "id", "in": "path", "required": True, "schema": {"type": "integer", "format": "int64"}}],
                "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": _envelope(None)}}}},
            },
        }

    doc = {
        "openapi": "3.1.0",
        "info": {
            "title": f"{system.display} API",
            "version": system.spec_version,
            "description": system.description or f"Generated by erp-spec-forge from YAML specs ({system.name}).",
        },
        "paths": paths,
        "components": {"schemas": schemas},
    }
    return doc
