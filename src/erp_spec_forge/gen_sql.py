"""MySQL 8 DDL generator (chosen target dialect, documented in README)."""
from __future__ import annotations

from .loader import System


def _sql_type(f) -> str:
    if f.type == "pk":
        return "BIGINT NOT NULL AUTO_INCREMENT"
    if f.type == "fk":
        return "BIGINT NULL" if not f.required else "BIGINT NOT NULL"
    if f.type == "string":
        return f"VARCHAR({f.length or 255})"
    if f.type == "text":
        return "TEXT"
    if f.type == "int":
        return "INT"
    if f.type == "decimal":
        return f"DECIMAL({f.precision[0]},{f.precision[1]})"
    if f.type == "bool":
        return "TINYINT(1)"
    if f.type == "date":
        return "DATE"
    if f.type == "datetime":
        return "DATETIME"
    if f.type == "enum":
        return "VARCHAR(32)"
    if f.type == "json":
        return "JSON"
    raise ValueError(f"unmapped type {f.type}")


def _default(f) -> str:
    if f.default is None:
        return ""
    if f.type == "datetime" and str(f.default).upper() == "CURRENT_TIMESTAMP":
        return " DEFAULT CURRENT_TIMESTAMP"
    if f.type in ("string", "enum", "text"):
        return f" DEFAULT '{f.default}'"
    return f" DEFAULT {f.default}"


def generate_sql(system: System) -> str:
    parts = [
        "-- Generated by erp-spec-forge, do not edit by hand.",
        f"-- System: {system.display} ({system.name}) | spec_version {system.spec_version} | dialect {system.dialect}",
        "SET NAMES utf8mb4;",
        "",
    ]
    entity_names = {e.name for e in system.entities}
    for d in system.domains:
        parts.append(f"-- ========== domain: {d.code} ({d.name}) ==========")
        for e in d.entities:
            cols, constraints, fks = [], [], []
            for f in e.fields:
                line = f"  `{f.name}` {_sql_type(f)}{_default(f)}"
                if f.comment:
                    line += f" COMMENT '{f.comment}'"
                cols.append(line)
                if f.type == "pk":
                    cols.append("  PRIMARY KEY (`id`)")
                if f.type == "enum" and f.values:
                    vals = ", ".join("'%s'" % v for v in f.values)
                    cols.append(f"  CHECK (`{f.name}` IN ({vals}))")
                if f.type == "fk" and f.target in entity_names:
                    fks.append(
                        f"  CONSTRAINT `fk_{e.name}_{f.name}` FOREIGN KEY (`{f.name}`) REFERENCES `{f.target}`(`id`)"
                    )
            # pk implicit if none declared -> validator flags it, but keep generator total
            body = cols + constraints + fks
            parts.append(f"CREATE TABLE `{e.name}` (")
            parts.append(",\n".join(body))
            parts.append(f") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='{e.display}';")
            parts.append("")
    return "\n".join(parts).rstrip() + "\n"
